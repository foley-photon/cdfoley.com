// Writes beta/conductance/js/engine/tables.js from _tests/conductance/fixtures/conductance-tables.json
// (spec 2.3 and Appendix A). The fixture's SHA-256 must match the value in the spec front matter.
// Usage: node _tests/conductance/tools/make-tables.mjs [--check]
//   --check  compare with the existing tables.js instead of writing it; exit 1 if they differ.
// The checksum is taken over the file with LF line endings, so a CRLF checkout (core.autocrlf) still verifies.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const FIXTURE = path.join(HERE, '..', 'fixtures', 'conductance-tables.json');
export const OUTPUT = path.join(HERE, '..', '..', '..', 'beta', 'conductance', 'js', 'engine', 'tables.js');
export const EXPECTED_SHA256 = '01d0e3e553d034b3fcd04c30692eb34dc36289acccc3cf0872a017e6718a06e6';
export const HEADER = '// GENERATED by _tests/conductance/tools/make-tables.mjs from conductance-tables.json — do not edit';
export const TABLE_KEYS = ['COLS_L', 'TUBE_IE', 'SLOT', 'RECT', 'ANNULUS', 'CONE', 'ELBOW', 'GP_SHARIPOV',
    'ORIFICE_A', 'FACETING', 'CLAUSING_PROFILE_LR20'];
const META_KEYS = ['format', 'version', 'generated', 'notes'];

/** SHA-256 (hex) of a text after normalizing CRLF to LF. */
export function sha256Lf(text) {
    return createHash('sha256').update(text.replace(/\r\n/g, '\n'), 'utf8').digest('hex');
}

/** Renders the tables module source from the fixture text; throws if the checksum or the keys are wrong. */
export function renderTablesModule(text) {
    const sha = sha256Lf(text);
    if (sha !== EXPECTED_SHA256) {
        throw new Error(`conductance-tables.json has SHA-256 ${sha}, expected ${EXPECTED_SHA256}. `
            + 'The fixture must be a verbatim copy of design/conductance-tables.json.');
    }
    const json = JSON.parse(text);
    if (json.format !== 'cdfoley-conductance-tables' || json.version !== 1) {
        throw new Error('Unexpected table format or version.');
    }
    const known = new Set([...TABLE_KEYS, ...META_KEYS, 'SOURCES']);
    const missing = [...TABLE_KEYS, 'SOURCES'].filter((k) => !(k in json));
    const extra = Object.keys(json).filter((k) => !known.has(k));
    if (missing.length || extra.length) {
        throw new Error(`Table keys differ from Appendix A (missing: ${missing.join(', ') || 'none'}; `
            + `unexpected: ${extra.join(', ') || 'none'}).`);
    }
    const meta = Object.fromEntries(META_KEYS.map((k) => [k, json[k]]));
    const out = [
        HEADER,
        `// Source SHA-256 (LF line endings): ${sha}`,
        '// Every export is deep-frozen data with the same name and structure as its JSON key (SOURCES -> TABLE_SOURCES).',
        'const F = (o) => { if (o && typeof o === \'object\') { for (const v of Object.values(o)) F(v); Object.freeze(o); } return o; };',
    ];
    for (const k of TABLE_KEYS) out.push(`export const ${k} = F(${JSON.stringify(json[k])});`);
    out.push(`export const TABLE_SOURCES = F(${JSON.stringify(json.SOURCES)});`);
    out.push(`export const TABLES_META = F(${JSON.stringify(meta)});`);
    return out.join('\n') + '\n';
}

function main() {
    const src = renderTablesModule(readFileSync(FIXTURE, 'utf8'));
    if (process.argv.includes('--check')) {
        const cur = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : null;
        if (cur !== src) {
            process.stderr.write('tables.js differs from the fixture; run make-tables.mjs without --check.\n');
            process.exit(1);
        }
        process.stdout.write(`tables.js is up to date (${Buffer.byteLength(src)} bytes).\n`);
        return;
    }
    writeFileSync(OUTPUT, src);
    process.stdout.write(`Wrote ${path.relative(process.cwd(), OUTPUT)} (${Buffer.byteLength(src)} bytes, SHA-256 of fixture verified).\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

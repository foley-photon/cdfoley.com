test('every embedded reference number equals its fixture entry exactly', () => {
    const without = [];
    for (const c of FORMULA_CASES) {
        const r = c.refFrom;
        if (!r) { without.push(c.id); continue; }
        const v = resolve(r.file, r.path);
        assert.notEqual(v, undefined, `${c.id}: fixture path ${r.path.join(' / ')} not found`);
        if (r.text) {
            assert.equal(typeof v, 'string', c.id);
            assert.ok(v.includes(r.text), `${c.id}: "${v}" does not contain "${r.text}"`);
        } else {
            assert.ok(Object.is(c.ref, v), `${c.id}: embedded ${c.ref}, fixture ${v}`);
        }
        if (r.sigmaPath) assert.ok(Object.is(c.refSigma, resolve(r.file, r.sigmaPath)), `${c.id} sigma`);
        else assert.equal(c.refSigma, 0, `${c.id}: refSigma without a fixture path`);
    }
    assert.deepEqual(without.sort(), Object.keys(NO_FIXTURE).sort());
    // computed references of formula cases: the published constants inside them
    const byId = Object.fromEntries(FORMULA_CASES.map((c) => [c.id, c]));
    assert.equal(byId['gp-sharipov-slip200'].ref, 200 / 4 + 1.018);
    assert.equal(byId['poiseuille-air'].ref, 1350);
    assert.equal(byId['square-duct-kv'].ref, 0.035144);
    assert.equal(byId['net-haefer-orifice-tube'].ref, 0.53766);
});


// ---- the tolerance logic of validation.js (spec 2.8, 5.1)
const C = (o) => ({ id: 'x', group: 'formula', title: 'A test case title', source: { label: 'L', url: '#how' }, ref: 1, refSigma: 0, quick: true, run: () => 1, ...o });

test('evaluate applies rel, abs, sigma and band tolerances at their limits', () => {
    const rel = C({ ref: 2, tol: { rel: 0.01 } });
    assert.equal(evaluate(rel, 2.0199).pass, true);
    assert.equal(evaluate(rel, 2.0201).pass, false);
    assert.equal(evaluate(rel, 1.9801).pass, true);
    assert.ok(Math.abs(evaluate(rel, 2.01).dev - 0.005) < 1e-15);
    assert.equal(evaluate(rel, 2.01).devText, '+0.500 %');
    assert.equal(evaluate(rel, 2).tolText, '±1 %');
    const abs = C({ ref: 0, tol: { abs: 1e-12 } });
    assert.equal(evaluate(abs, 9e-13).pass, true);
    assert.equal(evaluate(abs, -1.1e-12).pass, false);
    assert.equal(evaluate(abs, -1.1e-12).dev, -1.1e-12);
    // |value - ref| <= 3 sqrt(sigma^2 + refSigma^2) + plusRel |ref|: 3 * 0.005 + 0.01 = 0.025
    const sig = C({ ref: 1, refSigma: 0.003, tol: { sigmas: 3, plusRel: 0.01 } });
    assert.equal(evaluate(sig, { value: 1.0249, sigma: 0.004 }).pass, true);
    assert.equal(evaluate(sig, { value: 0.9749, sigma: 0.004 }).pass, false);
    assert.equal(evaluate(sig, { value: 1.0249, sigma: 0.004 }).sigma, 0.004);
    assert.equal(evaluate(sig, 1).tolText, '3σ + 1 %');
    // band: the reference must lie in [value (1 + lo), value (1 + hi)]
    const band = C({ ref: 1.05, tol: { band: true } });
    assert.equal(evaluate(band, { value: 1, band: { lo: -0.01, hi: 0.06 } }).pass, true);
    assert.equal(evaluate(band, { value: 1, band: { lo: -0.01, hi: 0.04 } }).pass, false);
    assert.equal(evaluate(band, { value: 1.07, band: { lo: -0.01, hi: 0.06 } }).pass, false);
    // an outcome may veto a pass, never grant one
    assert.equal(evaluate(rel, { value: 2, pass: false }).pass, false);
    assert.equal(evaluate(rel, { value: 3, pass: true }).pass, false);
});

test('evaluate: negative controls are caught beyond catchRel or by their own verdict; errors fail the row', () => {
    const neg = C({ group: 'negative', ref: 0.5, catchRel: 0.05, tol: { catchRel: 0.05 } });
    let r = evaluate(neg, 0.53);
    assert.equal(r.caught, true); assert.equal(r.pass, true);
    r = evaluate(neg, 0.51);
    assert.equal(r.caught, false); assert.equal(r.pass, false);
    assert.equal(evaluate(neg, 0.5).tolText, 'caught if |dev| > 5 %');
    const own = C({ group: 'negative', ref: 1, catchRel: 99, tol: null });
    assert.equal(evaluate(own, { value: 3, caught: true }).caught, true);
    assert.equal(evaluate(own, { value: NaN, sigma: 0, caught: true }).caught, true, 'verdict kept without a number');
    assert.equal(evaluate(own, { value: NaN, caught: false }).caught, false);
    const failed = evaluate(C({ tol: { rel: 0.1 } }), { error: 'boom' });
    assert.equal(failed.pass, false);
    assert.equal(failed.devText, 'Error: boom');
    assert.equal(evaluate(C({ tol: { rel: 0.1 } }), NaN).devText, 'No result');
    assert.equal(evaluate(C({ tol: { rel: 0.1 } }), NaN).caught, null, 'caught is null for ordinary cases');
});

test('runCases runs in order, turns throws into failed rows, stops on abort; summarize counts groups', async () => {
    const cases = [
        C({ id: 'a', tol: { rel: 0.1 }, run: () => 1.05 }),
        C({ id: 'b', group: 'chain-mc', tol: { sigmas: 3 }, run: async () => ({ value: 1.001, sigma: 0.001 }) }),
        C({ id: 'c', tol: { rel: 0.1 }, run: () => { throw new Error('no runner'); } }),
        C({ id: 'd', group: 'negative', catchRel: 0.05, tol: { catchRel: 0.05 }, run: () => 1.2 }),
        C({ id: 'e', group: 'mesh-mc', tol: { sigmas: 3 }, run: async () => ({ value: 2, sigma: 0.01 }) }),
    ];
    const seen = [];
    const rows = await runCases(cases, {}, (row, i) => seen.push([row.id, i]), undefined);
    assert.deepEqual(seen, [['a', 0], ['b', 1], ['c', 2], ['d', 3], ['e', 4]]);
    assert.deepEqual(rows.map((r) => r.pass), [true, true, false, true, false]);
    assert.equal(rows[2].devText, 'Error: no runner');
    assert.ok(rows.every((r) => r.ms >= 0));
    assert.deepEqual(summarize(rows), { formula: [1, 2], mc: [1, 2], negative: [1, 1] });
    const ac = new AbortController();
    const part = await runCases(cases, {}, (row) => { if (row.id === 'b') ac.abort(); }, ac.signal);
    assert.deepEqual(part.map((r) => r.id), ['a', 'b']);
    const ctxSeen = [];
    await runCases([C({ run: (ctx) => { ctxSeen.push(ctx); return 1; }, tol: { rel: 0.1 } })], { mc: 'runner' });
    assert.deepEqual(ctxSeen, [{ mc: 'runner' }]);
});

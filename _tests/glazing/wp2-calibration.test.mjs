test('coatings: structure, materials, bounds, calibratedTo = the class\'s calibration rows, residual formatting', () => {
    assert.deepEqual(Object.keys(C.coatings), CLASSES);
    for (const cls of CLASSES) {
        const c = C.coatings[cls], spec = CFG.classes[cls];
        assert.equal(c.label, spec.label);
        assert.equal(c.epsFrom, 'published U-factors, air and argon');
        assert.ok(c.eps > 0.005 && c.eps < 0.3 && Math.abs(c.eps * 1e4 - Math.round(c.eps * 1e4)) < 1e-6, cls + ' eps ' + c.eps);
        assert.equal(c.layers.length, spec.layers.length);
        c.layers.forEach((L, i) => {
            assert.equal(L.m, spec.layers[i][0]);
            assert.ok(M.materials[L.m], L.m);
            assert.ok(L.d >= spec.layers[i][2] && L.d <= spec.layers[i][3], `${cls} layer ${i} ${L.d}`);
            assert.ok(Math.abs(L.d * 100 - Math.round(L.d * 100)) < 1e-6, '2 decimals');
        });
        const ag = c.layers.filter(L => L.m === 'Ag').reduce((a, L) => a + L.d, 0);
        assert.ok(Math.abs(c.silverNm - ag) < 1e-9);
        const rows = PUB.rows.filter(r => r.class === cls && r.role === 'calibrate').map(r => r.id);
        assert.deepEqual(Array.from(c.calibratedTo), rows);
        assert.deepEqual(Object.keys(c.residuals), rows);
        for (const id of rows) {
            const row = PUB.rows.find(r => r.id === id), res = c.residuals[id];
            for (const q of ['VT', 'Rout', 'Rin', 'SHGC', 'Uair', 'Uar', 'U', 'UV', 'Tsol']) {
                if (row[q] == null) { assert.ok(!(q in res), id + ' ' + q); continue; }
                assert.equal(res[q].length, 2); assert.equal(res[q][1], row[q]);
            }
            assert.equal(res.colorR.length, 2); assert.equal(res.colorT.length, 2);
        }
    }
});

// Appendix A.5: the design-phase stacks. With the pre-audit engine the layers land within 0.2 nm (largest
// difference 0.15 nm, triple). The audited engine on main (its gas-mixture, indoor-convection and pillar fixes) moves
// SHGC slightly, and recalibrating with it moves the triple's shallow optimum by up to 0.42 nm (base Ag 8.83 against
// 9.05, spacer TiO2 47.18 against 47.60), so the bound is 0.5 nm. The emissivities depend on the thermal model: the
// pre-audit engine gives about 0.002 less than the design values, the audited engine reproduces them.
// Fix round 1 (2026-10-13): the UV term of the objective now uses LBNL WINDOW's TUV method (E891 points from 310 to
// 380 nm, trapezoid; GlazingBeta.tuvNFRC) instead of the engine's 300-380 nm bin average, which read 0.2 to 1.1
// points high. That moves the single-silver stack by up to 1.9 nm (top Si3N4 18.27 -> 20.15, TiO2 28.14 -> 27.24);
// its reference below is the recalibrated stack. The other classes stay within 0.5 nm of A.5.
const A5 = {
    hard: { eps: 0.163, d: [26.19, 18.91, 200.00, 38.13] },
    single: { eps: 0.071, d: [37.64, 8.76, 0.46, 27.24, 20.15] },
    double: { eps: 0.042, d: [33.42, 10.24, 1.63, 57.53, 14.42, 0, 31.25] },
    triple: { eps: 0.022, d: [5.00, 9.05, 0.88, 47.60, 15.87, 0, 62.47, 20.67, 0.62, 31.10] }
};
test('stacks within 0.5 nm of the design-phase optimum (A.5); eps within 0.005', t => {
    for (const cls of CLASSES) {
        const c = C.coatings[cls];
        const worst = Math.max(...c.layers.map((L, i) => Math.abs(L.d - A5[cls].d[i])));
        t.diagnostic(`${cls}: max layer difference ${worst.toFixed(2)} nm; eps ${c.eps} (A.5: ${A5[cls].eps})`);
        assert.ok(worst <= 0.5 + 1e-9, `${cls}: ${worst} nm`);
        assert.ok(Math.abs(c.eps - A5[cls].eps) <= 0.005, `${cls} eps ${c.eps}`);
    }
});

// ── V4 and V5 (spec 5.3) with the tolerances of 5.2 ───────────────────────────────────────────────────────
const TOL = {
    calibrate: { VT: 1.0, R: 2.0, SHGC: 0.015, U: 0.01, UV: 3, Tsol: 2.5 },
    check: { VT: 2.0, R: 2.5, SHGC: 0.02, U: 0.015, UV: 5, Tsol: 3 }
};
const WIN = CFG.windows.neutral;
function build(row, fill) {
    const L = row.panes.map(p => E.pane(p.glass, p.mm, p.coat || 'none', p.side || 'front', 'open'));
    return E.evaluate(L, row.gaps.map(w => ({ fill, width: w / 1000 })), 1, E891);
}
function verify(t, row) {
    const cal = row.role === 'calibrate', hard = row.class === 'hard', tol = Object.assign({}, TOL[row.role]);
    if (cal && row.class === 'triple') tol.R = 2.5;
    const report = hard ? ['VT', 'SHGC', 'UV', 'Tsol'] : [];        // 2011 sheet vs the measured product (2.6.5)
    const a = build(row, 'air'), r = row.Uar != null ? build(row, 'argon') : null;
    const got = { VT: 100 * a.Tvis, Rout: 100 * a.Rvis, Rin: 100 * a.RvisIn, SHGC: a.SHGC, Uair: a.U / BTU, Uar: r ? r.U / BTU : null,
        U: a.U / BTU, UV: 100 * tuvWindow(a.sys.T), Tsol: 100 * a.Tsol };   // UV: WINDOW's TUV, as the datasheets
    const tolOf = { VT: tol.VT, Rout: tol.R, Rin: tol.R, SHGC: tol.SHGC, Uair: tol.U, Uar: tol.U, U: tol.U, UV: tol.UV, Tsol: tol.Tsol };
    const misses = {};
    for (const q of Object.keys(tolOf)) {
        if (row[q] == null) continue;
        const d = got[q] - row[q];
        misses[q] = d;
        if (report.includes(q)) { t.diagnostic(`${row.id} ${q}: open ${got[q].toFixed(3)}, published ${row[q]} (report only)`); continue; }
        t.diagnostic(`${row.id} ${q}: open ${got[q].toFixed(3)}, published ${row[q]}, miss ${d.toFixed(4)} (tolerance ${tolOf[q]})`);
        assert.ok(Math.abs(d) <= tolOf[q] + 1e-12, `${row.id} ${q}: open ${got[q]}, published ${row[q]} (tolerance ${tolOf[q]})`);
    }
    if (cal && row.panes.length > 1) {      // the neutral window ±0.3 on the exterior reflected color
        const inW = (v, w) => v >= w[0] - 0.3 && v <= w[1] + 0.3;
        t.diagnostic(`${row.id} exterior a*, b*: ${a.colorR.a.toFixed(2)}, ${a.colorR.b.toFixed(2)}`);
        assert.ok(inW(a.colorR.a, WIN.Ra) && inW(a.colorR.b, WIN.Rb), `${row.id} exterior color ${a.colorR.a}, ${a.colorR.b}`);
    } else {
        t.diagnostic(`${row.id} exterior a*, b*: ${a.colorR.a.toFixed(2)}, ${a.colorR.b.toFixed(2)} (report only)`);
    }
    return misses;
}

const calRows = PUB.rows.filter(r => r.role === 'calibrate'), chkRows = PUB.rows.filter(r => r.role === 'check');
test('the published table has 9 calibration rows and 7 held-out rows', () => {
    assert.equal(calRows.length, 9);
    assert.equal(chkRows.length, 7);
});
for (const row of calRows) test('V4 ' + row.id + ' (' + row.class + ', calibration)', t => { verify(t, row); });
for (const row of chkRows) test('V5 ' + row.id + ' (' + row.class + ', held out)', t => { verify(t, row); });

test('the committed residuals equal a fresh computation through the page path', () => {
    for (const cls of CLASSES) for (const id of C.coatings[cls].calibratedTo) {
        const row = PUB.rows.find(r => r.id === id), a = build(row, 'air'), res = C.coatings[cls].residuals[id];
        assert.equal(res.VT[0], Number((100 * a.Tvis).toFixed(1)));
        assert.equal(res.SHGC[0], Number(a.SHGC.toFixed(3)));
        if (res.Uair) assert.equal(res.Uair[0], Number((a.U / BTU).toFixed(3)));
        assert.equal(res.colorR[0], Number(a.colorR.a.toFixed(2)));
    }
});

test('script functions: nelderMead is deterministic and minimizes; inferEps scans the stated grid', () => {
    const f = x => (x[0] - 3) ** 2 + 10 * (x[1] + 1) ** 2;
    const a = CAL.nelderMead(f, [0, 0], [1, 1], 200), b = CAL.nelderMead(f, [0, 0], [1, 1], 200);
    assert.deepEqual(a, b);
    assert.ok(Math.abs(a.x[0] - 3) < 1e-6 && Math.abs(a.x[1] + 1) < 1e-6);
    const e = CAL.inferEps('single', C.coatings.single.layers);
    assert.ok(Math.abs(e - C.coatings.single.eps) < 1e-9, String(e));
    const k = Math.round((e - 0.005) / 0.0005);
    assert.ok(Math.abs(0.005 + k * 0.0005 - e) < 1e-12);
    assert.equal(CAL.inferEps('hard', C.coatings.hard.layers) > 0.1, true);
    assert.ok(CAL.objective([1, 2, 3], 'hard', 0.16) === 1e9, 'out of bounds');
});

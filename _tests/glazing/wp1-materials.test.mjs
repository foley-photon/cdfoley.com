// A temporary copy of everything the generator reads, laid out like the repo.
const INPUTS = [GEN, SOURCES, 'assets/js/glazing-weights.js',
    ...fs.readdirSync(path.join(ROOT, '_scripts/data/rii')).map(f => '_scripts/data/rii/' + f),
    ...fs.readdirSync(path.join(ROOT, '_scripts/data/wce')).map(f => '_scripts/data/wce/' + f)];
const temps = [];
function tempCopy() {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'glazing-wp1-'));
    temps.push(dir);
    for (const rel of INPUTS) {
        fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
        fs.copyFileSync(path.join(ROOT, rel), path.join(dir, rel));
    }
    return dir;
}
const run = (dir, ...args) => spawnSync(PY, [path.join(dir, GEN), ...args], { cwd: dir, encoding: 'utf8' });
test.after(() => { for (const d of temps) fs.rmSync(d, { recursive: true, force: true }); });

test('V9.1 the generator is deterministic and the committed files are its output', () => {
    const dir = tempCopy();
    const r1 = run(dir);
    assert.equal(r1.status, 0, r1.stderr);
    const a = [OUT, OUT_E891].map(f => fs.readFileSync(path.join(dir, f)));
    const r2 = run(dir);
    assert.equal(r2.status, 0, r2.stderr);
    const b = [OUT, OUT_E891].map(f => fs.readFileSync(path.join(dir, f)));
    for (let i = 0; i < 2; i++) {
        assert.ok(a[i].equals(b[i]), 'second run differs: ' + [OUT, OUT_E891][i]);
        assert.ok(!a[i].includes(13), 'output must be LF only: ' + [OUT, OUT_E891][i]);
        assert.equal(a[i].toString('utf8'), text([OUT, OUT_E891][i]), 'committed file is not the generator output: ' + [OUT, OUT_E891][i]);
    }
});

test('V9.2 --check passes on the committed files and fails on a stale one', () => {
    const ok = spawnSync(PY, [path.join(ROOT, GEN), '--check'], { cwd: ROOT, encoding: 'utf8' });
    assert.equal(ok.status, 0, ok.stderr);
    const dir = tempCopy();
    assert.equal(run(dir).status, 0);
    fs.appendFileSync(path.join(dir, OUT_E891), '// stale\n');
    const bad = run(dir, '--check');
    assert.equal(bad.status, 1);
    assert.match(bad.stderr, /glazing-solar-e891\.js/);
    // --check never writes.
    assert.ok(fs.readFileSync(path.join(dir, OUT_E891), 'utf8').endsWith('// stale\n'));
});

test('V9.3 a one-byte change to any pinned input stops the generator and names the file', () => {
    const dir = tempCopy();
    const files = [...S.materials.map(m => localName(m.path)), S.refractiveindex.licenseFile.file, S.solarE891.file,
        S.solarE891.licenseFile.file];
    assert.equal(files.length, 14);
    for (const rel of files) {
        const p = path.join(dir, '_scripts/data', rel), orig = fs.readFileSync(p);
        const changed = Buffer.from(orig);
        changed[changed.length >> 1] ^= 0x01;                          // flip one bit of one byte
        fs.writeFileSync(p, changed);
        const r = run(dir);
        fs.writeFileSync(p, orig);
        assert.equal(r.status, 1, rel + ': expected exit 1');
        assert.ok(r.stderr.includes(rel), rel + ': the message must name the file, got: ' + r.stderr);
        assert.ok(!fs.existsSync(path.join(dir, OUT)), 'nothing is written when an input fails');
    }
});


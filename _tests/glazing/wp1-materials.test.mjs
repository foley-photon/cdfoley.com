// V9, materials generator (glazing beta build spec, sections 2.1, 6.4 and 5.3 V9). Checks that
// _scripts/build_glazing_materials.py is deterministic and pinned (a one-byte change to any input stops it),
// that the committed assets/js/glazing-materials.js is its current output, and that the 14 materials carry the
// optical constants the coating calibration was made with. Run: node --test "_tests/glazing/**/*.test.mjs"
// Needs Python 3 on PATH as `python` (or set PYTHON). The generator runs in a temporary copy of its inputs.

// Independent re-evaluation of the physics in JavaScript, from glazing_sources.json and the YAML coefficients.
const cx = (re, im = 0) => ({ re, im });
const add = (a, b) => cx(a.re + b.re, a.im + b.im), sub = (a, b) => cx(a.re - b.re, a.im - b.im);
const mul = (a, b) => cx(a.re * b.re - a.im * b.im, a.re * b.im + a.im * b.re);
const div = (a, b) => { const d = b.re * b.re + b.im * b.im; return cx((a.re * b.re + a.im * b.im) / d, (a.im * b.re - a.re * b.im) / d); };
const csqrt = a => { const r = Math.hypot(a.re, a.im), re = Math.sqrt((r + a.re) / 2), im = Math.sqrt(Math.max(0, (r - a.re) / 2)); return cx(re, a.im < 0 ? -im : im); };
function dl(p, nm) {
    const E = 1239.84198 / nm;
    let eps = cx(p.einf);
    if (p.AD) eps = sub(eps, div(cx(p.AD), cx(E * E, p.GD * E)));
    if (p.AL) eps = add(eps, div(cx(p.AL), cx(p.EL * p.EL - E * E, -p.GL * E)));
    return eps;
}
const near = (got, exp, digits, what) => assert.ok(Math.abs(got - exp) <= Math.abs(exp) * 0.6 * 10 ** (1 - digits) + 1e-12, what + ': ' + got + ' vs ' + exp);

test('V9.9 the tin-oxide models and the Bruggeman layer re-evaluate to the stored values', () => {
    const P = Object.fromEntries(S.models.map(m => [m.id, m]));
    assert.deepEqual([P.SnO2.einf, P.SnO2.AL, P.SnO2.GL, P.SnO2.EL], [3.70, 0.417, 0.5064, 3.386]);
    assert.deepEqual([P.FTO.einf, P.FTO.AD, P.FTO.GD, P.FTO.AL, P.FTO.GL, P.FTO.EL], [3.19, 2.173, 0.167, 24.67, 0.1275, 5.26]);
    for (const nm of [300, 550, 1000, 2000, 2500]) {
        const i = at(nm);
        for (const id of ['SnO2', 'FTO']) {
            const N = csqrt(dl(P[id], nm));
            near(mat(id).n[i], N.re, 5, id + ' n ' + nm);
            near(mat(id).k[i], N.im, 4, id + ' k ' + nm);
        }
        // Bruggeman, 50 % void: 2e^2 - B e - eh = 0, B = (3fh - 1) eh + (3fv - 1); the root with Im >= 0.
        const eh = dl(P.FTO, nm), f = 1 - P.FTO_rough.fvoid;
        const B = add(mul(cx(3 * f - 1), eh), cx(3 * P.FTO_rough.fvoid - 1));
        const disc = csqrt(add(mul(B, B), mul(cx(8), eh)));
        const roots = [div(add(B, disc), cx(4)), div(sub(B, disc), cx(4))].filter(r => r.im >= -1e-12).sort((a, b) => b.re - a.re);
        const e = roots[0];
        assert.ok(Math.abs(2 * (e.re * e.re - e.im * e.im) - (B.re * e.re - B.im * e.im) - eh.re) < 1e-9, 'root solves the quadratic');
        const N = csqrt(e);
        near(mat('FTO_rough').n[i], N.re, 5, 'FTO_rough n ' + nm);
        near(mat('FTO_rough').k[i], N.im, 4, 'FTO_rough k ' + nm);
    }
});

test('V9.10 the dispersion formulas re-evaluate to the stored values', () => {
    const yml = id => fs.readFileSync(path.join(ROOT, '_scripts/data', localName(S.materials.find(m => m.id === id).path)), 'utf8');
    const coef = (id, type) => {
        const part = yml(id).split(/\n\s*-\s*type:\s*/).find(p => p.startsWith(type));
        return {
            c: part.match(/coefficients:\s*([^\n]+)/)[1].trim().split(/\s+/).map(Number),
            r: part.match(/wavelength_range:\s*([^\n]+)/)[1].trim().split(/\s+/).map(Number)
        };
    };
    for (const id of ['SiO2', 'Si3N4']) {                                // formula 1 (Sellmeier)
        const { c, r } = coef(id, 'formula 1');
        for (const nm of [300, 550, 1550, 2500]) {
            const x = Math.min(Math.max(nm / 1000, r[0]), r[1]);
            let s = 1 + c[0];
            for (let j = 1; j + 1 < c.length; j += 2) s += c[j] * x * x / (x * x - c[j + 1] * c[j + 1]);
            near(mat(id).n[at(nm)], Math.sqrt(s), 5, id + ' n ' + nm);
        }
    }
    for (const id of IDS.filter(x => x.startsWith('glass_'))) {         // formula 5, clamped to its range
        const { c, r } = coef(id, 'formula 5');
        for (const nm of [300, 305, 310, 550, 1000, 2500]) {
            const x = Math.min(Math.max(nm / 1000, r[0]), r[1]);
            let s = c[0];
            for (let j = 1; j + 1 < c.length; j += 2) s += c[j] * x ** c[j + 1];
            near(mat(id).n[at(nm)], s, 5, id + ' n ' + nm);
        }
        // tabulated k, clamped below the table: the first grid values repeat the first table value
        assert.equal(mat(id).k[0], mat(id).k[at(Math.round(1000 * Number(yml(id).match(/tabulated k\s+data:\s*\|\s*\n\s*([0-9.]+)/)[1])))], id);
    }
});

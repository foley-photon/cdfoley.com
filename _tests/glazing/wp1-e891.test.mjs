// V10, ASTM E891 solar weights (glazing beta build spec, sections 2.2, 6.4 and 5.3 V10). Checks the generated
// assets/js/glazing-solar-e891.js: 441 weights summing to 1, the visible fraction, equality with the staged
// prototype the coatings were calibrated with, an independent re-integration of the Windows-CalcEngine table,
// and the BSD header that reproduces the full License.txt. Run: node --test "_tests/glazing/**/*.test.mjs"
import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { load, ROOT } from './helpers/load.mjs';

const OUT = 'assets/js/glazing-solar-e891.js';
const lf = s => s.replace(/\r\n/g, '\n');
const ctx = load(['assets/js/glazing-weights.js', OUT]);
const S = ctx.GlazingSolarE891, Wt = ctx.GlazingWeights;
const w = Array.from(S.solarE891);
const LAM = Array.from({ length: 441 }, (_, i) => 300 + 5 * i);
const sum = a => a.reduce((s, x) => s + x, 0);
const visFrac = a => sum(a.filter((_, i) => LAM[i] >= 380 && LAM[i] <= 780));

// SHA-256 of JSON.stringify(solarE891) of the staged prototype (design\glazing-proto\glazing-solar-e891.js,
// 2026-10-12), used by the coating calibration. A change means recalibrating (spec 7.2).
const PROTOTYPE = '391777c60b1adef95e1dd958a0fb3dd41a38ba8bcad0381ef940ffcbfce6db23';

test('V10.1 441 weights, sum 1, visible fraction 0.499', () => {
    assert.deepEqual({ ...S.grid }, { start: 300, step: 5, n: 441 });
    assert.equal(w.length, 441);
    assert.ok(w.every(x => Number.isFinite(x) && x >= 0));
    assert.ok(Math.abs(sum(w) - 1) <= 1e-5, 'sum ' + sum(w));
    const v = visFrac(w);
    assert.ok(Math.abs(v - 0.499) <= 0.002, '380-780 nm fraction ' + v);
    // For reference, the live page's G173 weighting puts 0.529 in the visible.
    assert.ok(Math.abs(visFrac(Array.from(Wt.solar)) - 0.529) <= 0.002);
    assert.equal(w[0] > 0 && w[0] < 1e-5, true, 'the first bin holds only the 300-302.5 nm half bin');
});

test('V10.2 equal to the staged prototype', () => {
    assert.equal(crypto.createHash('sha256').update(JSON.stringify(w)).digest('hex'), PROTOTYPE);
});

test('V10.3 an independent re-integration of the E891 table reproduces the weights', () => {
    const cpp = fs.readFileSync(path.join(ROOT, '_scripts/data/wce/standardData.cpp'), 'utf8');
    const i = cpp.indexOf('solarRadiationASTM_E891_87_Table1()');
    const body = cpp.slice(cpp.indexOf('return', i), cpp.indexOf('};', i));
    const t = [...body.matchAll(/\{\s*([0-9.]+)\s*,\s*([0-9.eE+-]+)\s*\}/g)].map(m => [Number(m[1]) * 1000, Number(m[2])]);
    assert.equal(t.length, 121);
    assert.equal(t[0][0], 300);
    assert.ok(Math.abs(t[t.length - 1][0] - 4045) < 1e-9);
    const f = x => {
        if (x < t[0][0] || x > t[t.length - 1][0]) return 0;
        let j = 0;
        while (t[j + 1][0] < x) j++;
        return t[j][1] + (x - t[j][0]) / (t[j + 1][0] - t[j][0]) * (t[j + 1][1] - t[j][1]);
    };
    // 5 nm bins [c - 2.5, c + 2.5), 20 midpoint sub-steps of 0.25 nm, as _scripts/build_glazing_weights.py.
    const raw = LAM.map(c => { let s = 0; for (let k = 0; k < 20; k++) s += f(c - 2.5 + 0.125 + 0.25 * k) * 0.25; return s; });
    const tot = sum(raw);
    raw.forEach((r, k) => {
        const exp = r / tot;
        assert.ok(Math.abs(w[k] - exp) <= exp * 5e-6 + 1e-15, LAM[k] + ' nm: ' + w[k] + ' vs ' + exp);
    });
});

test('V10.4 header of spec 6.4 with the full Windows-CalcEngine license text', () => {
    const src = lf(fs.readFileSync(path.join(ROOT, OUT), 'utf8'));
    const license = lf(fs.readFileSync(path.join(ROOT, '_scripts/data/wce/License.txt'), 'utf8'));
    const header =
        '/* ASTM E891-87 Table 1 direct normal solar spectrum (AM1.5), as tabulated in LBNL Windows-CalcEngine\n' +
        '   src/helper/optical/standardData.cpp (commit 1dedefa), integrated into the 5 nm bins of glazing-weights.js\n' +
        '   and normalized over 300-2500 nm. Generated by _scripts/build_glazing_materials.py. Do not edit by hand.\n' +
        '   The source file is distributed under the following license:\n' +
        '\n' +
        license.split('\n').map(l => '   ' + l).join('\n') + ' */\n';
    assert.ok(src.startsWith(header), 'header with the verbatim License.txt, each line indented by three spaces');
    assert.ok(src.includes('Copyright (c) 2016, The Regents of the University of California'));
    assert.ok(src.includes('THIS SOFTWARE IS PROVIDED BY THE COPYRIGHT HOLDERS AND CONTRIBUTORS "AS IS"'));
    assert.ok(!src.includes('\r'));
    // The weights are the only code: one UMD wrapper setting window.GlazingSolarE891 and module.exports.
    assert.ok(src.slice(header.length).startsWith('(function (root) {\n'));
    assert.match(src, /root\.GlazingSolarE891 = S;\n    if \(typeof module !== 'undefined'\) module\.exports = S;\n\}\)\(typeof window !== 'undefined' \? window : globalThis\);\n$/);
});

test('V10.5 the engine accepts the weights as opts.solar', () => {
    const c = load(['assets/js/glazing-weights.js', 'assets/js/glazing-engine.js', OUT]);
    const E = c.GlazingEngine, layer = E.pane('clear', 6, 'none', 'front');
    const g = E.evaluate([layer], [], 1), e = E.evaluate([layer], [], 1, { solar: c.GlazingSolarE891.solarE891 });
    assert.ok(Number.isFinite(e.Tsol) && Math.abs(e.Tsol - g.Tsol) > 1e-4 && Math.abs(e.Tsol - g.Tsol) < 0.02);
    assert.equal(e.Tvis, g.Tvis);
});

test('V10.6 tuvTable: the E891 table points from 310 to 380 nm, as typed in standardData.cpp (WINDOW\'s TUV method)', () => {
    assert.deepEqual(JSON.parse(JSON.stringify(S.tuvTable)), [[310, 15.6], [315, 41.1], [320, 71.2], [325, 100.2], [330, 152.4], [335, 155.6],
        [340, 179.4], [345, 186.7], [350, 212], [360, 240.5], [370, 324], [380, 362.4]]);
});

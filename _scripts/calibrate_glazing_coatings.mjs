// Offline calibration of the open glazing model's generic low-e coatings (glazing beta build spec, 2.6).
//
// Fits the layer thicknesses of four generic stacks (pyrolytic hard coat, single, double and triple silver)
// ONLY to published manufacturer datasheet values: the rows of assets/data/glazing/published.json with
// role "calibrate" (VT, visible reflectance out and in, SHGC, UV (WINDOW's TUV method) and solar transmittance where published),
// with the exterior-reflected and transmitted color held inside windows taken from the manufacturers'
// published appearance statements. The coated-face emissivity is then inferred from the published air and
// argon U-factors by least squares. No measured IGDB spectra and no IGDB-derived numbers enter the fit.
//
// Optics: normal-incidence characteristic-matrix thin-film model (H. A. Macleod, Thin-Film Optical
// Filters) through the shipped glazing-tmm.js and glazing-open.js; thermal: the shipped ISO 15099
// glazing-engine.js. Minimizer: Nelder-Mead downhill simplex (J. A. Nelder and R. Mead, Comput. J. 7,
// 308-313 (1965)), deterministic (no random numbers).
//
// Usage (Node 22+, from the repository root or anywhere):
//   node _scripts/calibrate_glazing_coatings.mjs                 calibrate all classes, write assets/js/glazing-coatings.js
//   node _scripts/calibrate_glazing_coatings.mjs --class=single  calibrate one class (or a comma list) and print it;
//                                                                writes nothing unless --out=<file> is given
//   node _scripts/calibrate_glazing_coatings.mjs --check         recompute the committed residuals; exit 1 on drift
//   --date=YYYY-MM-DD sets the "version" field (default: today, UTC).
//
// The same inputs give a byte-identical output on the same Node major version (transcendental functions may
// differ in the last bit between versions; --check tolerates that).
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FILES = {
    weights: 'assets/js/glazing-weights.js',
    engine: 'assets/js/glazing-engine.js',
    materials: 'assets/js/glazing-materials.js',
    e891: 'assets/js/glazing-solar-e891.js',
    tmm: 'assets/js/glazing-tmm.js',
    coatings: 'assets/js/glazing-coatings.js',
    open: 'assets/js/glazing-open.js',
    core: 'beta/glazing/beta-core.js',    // GlazingBeta.tuvNFRC: the datasheets' UV transmittance (WINDOW's TUV method)
    published: 'assets/data/glazing/published.json',
    config: '_scripts/glazing_calibration.json'
};
export const BTU = 5.678263;          // W/m²·K per Btu/h·ft²·°F
export const CLASSES = ['hard', 'single', 'double', 'triple'];
// --check tolerances (spec 2.6.7): percent points for VT, R, UV and Tsol; fractions for SHGC; Btu for U; CIELAB units.
export const CHECK_TOL = { VT: 0.15, Rout: 0.15, Rin: 0.15, UV: 0.15, Tsol: 0.15, SHGC: 0.002, Uair: 0.002, Uar: 0.002, U: 0.002, colorR: 0.1, colorT: 0.1 };
export const HEADER = '/* Calibrated generic low-e coating stacks for the open-data glazing model.\n' +
    '   Generated by _scripts/calibrate_glazing_coatings.mjs. Do not edit by hand.\n' +
    '   Layer thicknesses were fitted only to published manufacturer datasheet values (assets/data/glazing/published.json);\n' +
    '   no measured IGDB spectra were used. The stacks are effective models, not any manufacturer\'s actual design. */\n';

// Procedure constants (spec 2.6.4), as in the design-phase prototype.
const PASSES = 3, RESTARTS = 4, ITERS = 500;
const STEP_FRACTION = [0.12, 0.05, 0.12, 0.05];   // initial simplex step, fraction of the bound width, per restart
const STEP_FLOOR = 0.3;                            // nm: smallest initial step (narrow Ni bounds)
const EPS_SCAN = { from: 0.005, to: 0.300, step: 0.0005 };

// ── Files ────────────────────────────────────────────────────────────────────────────────────────────────
export const abs = rel => path.resolve(ROOT, rel);
export const readText = file => fs.readFileSync(path.isAbsolute(file) ? file : abs(file), 'utf8').replace(/\r\n/g, '\n');
export const sha256 = text => crypto.createHash('sha256').update(text, 'utf8').digest('hex');
export function inputHashes() {   // of LF-normalized text (spec G10)
    return { engine: sha256(readText(FILES.engine)), materials: sha256(readText(FILES.materials)),
        published: sha256(readText(FILES.published)), config: sha256(readText(FILES.config)) };
}

// Load the shipped classic scripts into a fresh node:vm context in page order, exactly like
// _tests/glazing/helpers/load.mjs: on Node 22.8+ the context is an ordinary global object
// (vm.constants.DONT_CONTEXTIFY), which runs the engine as fast as the main realm.
export function loadModules(coatingsFile) {
    const host = { console, performance, TextDecoder, TextEncoder, setTimeout, clearTimeout, queueMicrotask };
    let ctx;
    if (vm.constants && vm.constants.DONT_CONTEXTIFY !== undefined) {
        ctx = vm.createContext(vm.constants.DONT_CONTEXTIFY);
        for (const k of Object.keys(host)) ctx[k] = host[k];
    } else {
        ctx = vm.createContext(host);
    }
    ctx.window = ctx;
    const list = [FILES.weights, FILES.engine, FILES.materials, FILES.e891, FILES.tmm];
    if (coatingsFile) list.push(coatingsFile);
    list.push(FILES.open, FILES.core);
    for (const f of list) {
        const file = path.isAbsolute(f) ? f : abs(f);
        vm.runInContext(fs.readFileSync(file, 'utf8'), ctx, { filename: file });
    }
    return ctx;
}

// An environment: the loaded modules plus the published rows and the configuration.
// coatingsFile: null to calibrate (the open model is used through stackPane only), or the coatings file to check.
export function makeEnv(coatingsFile = null) {
    const ctx = loadModules(coatingsFile);
    const CFG = JSON.parse(readText(FILES.config)), PUB = JSON.parse(readText(FILES.published));
    if (CFG.solar !== 'E891') throw new Error('calibrate: only "solar": "E891" is supported');
    const solar = ctx.GlazingSolarE891.solarE891, tuvTable = ctx.GlazingSolarE891.tuvTable;
    if (!tuvTable) throw new Error('calibrate: glazing-solar-e891.js has no tuvTable; rerun python _scripts/build_glazing_materials.py');
    // UV as the datasheets publish it: LBNL WINDOW's TUV (E891 points from 310 to 380 nm, trapezoidal rule), not the
    // engine's 300-380 nm bin average (r.Tuv), which reads 0.2 to 1.1 points higher on the published rows.
    const tuv = r => ctx.GlazingBeta.tuvNFRC(r.sys.T, tuvTable);
    return { ctx, E: ctx.GlazingEngine, O: ctx.GlazingOpen, C: ctx.GlazingCoatings || null, CFG, PUB, opts: { solar }, tuv };
}
let DEFAULT_ENV = null;
const defaultEnv = () => DEFAULT_ENV || (DEFAULT_ENV = makeEnv(null));

export const calibrationRows = (cls, env = defaultEnv()) => env.PUB.rows.filter(r => r.class === cls && r.role === 'calibrate');
export const layersOf = (cls, x, env = defaultEnv()) => env.CFG.classes[cls].layers.map((s, i) => ({ m: s[0], d: x[i] }));

// ── Model of one published row ───────────────────────────────────────────────────────────────────────────
// The row's own glass, thicknesses and surfaces; every coated pane gets `layers` with emissivity eps on the
// coated face. fill: 'air' or 'argon' for every gap. H = 1 m; E891 solar weights.
export function buildRow(row, layers, eps, fill, env = defaultEnv()) {
    const { E, O } = env;
    const L = row.panes.map(p => p.coat
        ? O.stackPane(p.glass, p.mm, layers, eps, p.side)
        : O.stackPane(p.glass, p.mm, null, E.EPS_GLASS, 'front'));
    const gaps = row.gaps.map(w => ({ fill, width: w / 1000 }));
    return E.evaluate(L, gaps, 1, env.opts);
}

const excess = (v, w) => (v < w[0] ? w[0] - v : v > w[1] ? v - w[1] : 0);

// ── Objective (spec 2.6.3), summed over the class's calibration rows ─────────────────────────────────────
export function objective(x, cls, eps, env = defaultEnv()) {
    const spec = env.CFG.classes[cls], specL = spec.layers;
    for (let i = 0; i < x.length; i++) if (!(x[i] >= specL[i][2] && x[i] <= specL[i][3])) return 1e9;
    const s = Object.assign({}, env.CFG.sigma, spec.sigmaOverride || {}), win = env.CFG.windows[spec.window];
    const layers = layersOf(cls, x, env);
    let e = 0;
    for (const row of calibrationRows(cls, env)) {
        const r = buildRow(row, layers, eps, 'air', env);
        e += ((r.Tvis - row.VT / 100) / s.VT) ** 2 + ((r.SHGC - row.SHGC) / s.SHGC) ** 2;
        if (row.Rout != null) e += ((r.Rvis - row.Rout / 100) / s.R) ** 2;
        if (row.Rin != null) e += ((r.RvisIn - row.Rin / 100) / s.R) ** 2;
        if (row.UV != null) e += ((env.tuv(r) - row.UV / 100) / s.UV) ** 2;
        if (row.Tsol != null) e += ((r.Tsol - row.Tsol / 100) / s.Tsol) ** 2;
        if (row.panes.length > 1) {           // color windows: IGU rows only
            e += (excess(r.colorR.a, win.Ra) / s.colorR) ** 2 + (excess(r.colorR.b, win.Rb) / s.colorR) ** 2;
            e += (excess(r.colorT.a, win.Ta) / s.colorT) ** 2 + (excess(r.colorT.b, win.Tb) / s.colorT) ** 2;
        }
    }
    // Regularization toward the start point, weight sigma.reg (as in the design-phase prototype).
    for (let i = 0; i < x.length; i++) { const x0 = specL[i][1]; e += s.reg * ((x[i] - x0) / (x0 + 2)) ** 2; }
    return e;
}

// ── Nelder-Mead (the prototype's: reflection 1, expansion 2, contraction 0.5, shrink 0.5) ────────────────
export function nelderMead(f, x0, step, iters) {
    const n = x0.length;
    let pts = [x0.slice()];
    for (let i = 0; i < n; i++) { const p = x0.slice(); p[i] += step[i]; pts.push(p); }
    let vals = pts.map(f);
    for (let it = 0; it < iters; it++) {
        const idx = vals.map((v, i) => i).sort((a, b) => vals[a] - vals[b]);
        pts = idx.map(i => pts[i]); vals = idx.map(i => vals[i]);
        const c = new Array(n).fill(0);
        for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) c[j] += pts[i][j] / n;
        const w = pts[n], xr = c.map((cj, j) => cj + (cj - w[j])), fr = f(xr);
        if (fr < vals[0]) {
            const xe = c.map((cj, j) => cj + 2 * (cj - w[j])), fe = f(xe);
            if (fe < fr) { pts[n] = xe; vals[n] = fe; } else { pts[n] = xr; vals[n] = fr; }
        } else if (fr < vals[n - 1]) {
            pts[n] = xr; vals[n] = fr;
        } else {
            const xc = c.map((cj, j) => cj + 0.5 * (w[j] - cj)), fc = f(xc);
            if (fc < vals[n]) { pts[n] = xc; vals[n] = fc; } else {
                for (let i = 1; i <= n; i++) { pts[i] = pts[i].map((v, j) => pts[0][j] + 0.5 * (v - pts[0][j])); vals[i] = f(pts[i]); }
            }
        }
    }
    const b = vals.indexOf(Math.min(...vals));
    return { x: pts[b], f: vals[b] };
}

// ── Emissivity from the published U-factors (spec 2.6.4) ────────────────────────────────────────────────
// Least squares of (U_air − U_air,pub)² + (U_ar − U_ar,pub)² over the class's calibration rows that publish
// both, scanning eps from 0.005 to 0.300 in steps of 0.0005 (the first minimum wins). null if no row has both.
export function inferEps(cls, layers, env = defaultEnv()) {
    const rows = calibrationRows(cls, env).filter(r => r.Uair != null && r.Uar != null);
    if (!rows.length) return null;
    const { E, O } = env;
    // The optics do not depend on eps: build each row's panes once, then set the coated faces' emissivity.
    // (Identical numbers to buildRow(row, layers, e, fill), which would recompute the same films.)
    const built = rows.map(row => ({
        row,
        panes: row.panes.map(p => ({ p, layer: p.coat ? O.stackPane(p.glass, p.mm, layers, 1, p.side) : O.stackPane(p.glass, p.mm, null, E.EPS_GLASS, 'front') }))
    }));
    const U = (b, e, fill) => E.evaluate(b.panes.map(({ p, layer }) => (p.coat ? Object.assign({}, layer, p.side === 'back' ? { eb: e } : { ef: e }) : layer)),
        b.row.gaps.map(w => ({ fill, width: w / 1000 })), 1, env.opts).U / BTU;
    const nSteps = Math.round((EPS_SCAN.to - EPS_SCAN.from) / EPS_SCAN.step);
    let best = null, bestErr = Infinity;
    for (let i = 0; i <= nSteps; i++) {
        const e = EPS_SCAN.from + i * EPS_SCAN.step;
        let err = 0;
        for (const b of built) err += (U(b, e, 'air') - b.row.Uair) ** 2 + (U(b, e, 'argon') - b.row.Uar) ** 2;
        if (err < bestErr) { bestErr = err; best = e; }
    }
    return best;
}

// ── One class ────────────────────────────────────────────────────────────────────────────────────────────
export function run(cls, env = defaultEnv(), log = () => {}) {
    const spec = env.CFG.classes[cls];
    if (!spec) throw new Error('calibrate: unknown class ' + cls);
    const specL = spec.layers, x0 = specL.map(s => s[1]);
    let eps = spec.eps0;
    if (!(eps > 0)) throw new Error('calibrate: class ' + cls + ' needs eps0');
    const t0 = Date.now();
    let best = { x: x0.slice(), f: objective(x0, cls, eps, env) };
    for (let pass = 0; pass < PASSES; pass++) {
        for (let r = 0; r < RESTARTS; r++) {
            const step = specL.map(s => Math.max(STEP_FLOOR, (s[3] - s[2]) * STEP_FRACTION[r]));
            const res = nelderMead(x => objective(x, cls, eps, env), best.x, step, ITERS);
            if (res.f < best.f) best = res;
        }
        const e = inferEps(cls, layersOf(cls, best.x, env), env);
        if (e != null) eps = e;
        best = { x: best.x, f: objective(best.x, cls, eps, env) };
        log(`  ${cls} pass ${pass + 1}: objective ${best.f.toFixed(3)}, eps ${eps.toFixed(4)}, ${((Date.now() - t0) / 1000).toFixed(0)} s`);
    }
    return { cls, x: best.x, f: best.f, eps, seconds: (Date.now() - t0) / 1000 };
}

// ── Output ───────────────────────────────────────────────────────────────────────────────────────────────
const fixed = (v, d) => { const s = v.toFixed(d); return Number(s) === 0 ? (0).toFixed(d) : s; };   // no "-0.00"
const pct = v => fixed(100 * v, 1);

// The shipped stack of a result: thicknesses to 2 decimals, eps to 4 (what the page will compute with).
export function shipped(result, env = defaultEnv()) {
    return {
        layers: layersOf(result.cls, result.x, env).map(L => ({ m: L.m, d: Number(fixed(L.d, 2)) })),
        eps: Number(fixed(result.eps, 4))
    };
}

// Residuals of one row: { quantity: [model text, published] } for what the row publishes, plus the exterior
// reflected and transmitted CIELAB a*, b* of the model. Model values are display-rounded strings.
export function rowResiduals(row, layers, eps, env = defaultEnv()) {
    const ra = buildRow(row, layers, eps, 'air', env);
    const rr = row.Uar != null ? buildRow(row, layers, eps, 'argon', env) : null;
    const out = {};
    if (row.VT != null) out.VT = [pct(ra.Tvis), row.VT];
    if (row.Rout != null) out.Rout = [pct(ra.Rvis), row.Rout];
    if (row.Rin != null) out.Rin = [pct(ra.RvisIn), row.Rin];
    if (row.SHGC != null) out.SHGC = [fixed(ra.SHGC, 3), row.SHGC];
    if (row.Uair != null) out.Uair = [fixed(ra.U / BTU, 3), row.Uair];
    if (rr) out.Uar = [fixed(rr.U / BTU, 3), row.Uar];
    if (row.U != null) out.U = [fixed(ra.U / BTU, 3), row.U];
    if (row.UV != null) out.UV = [pct(env.tuv(ra)), row.UV];
    if (row.Tsol != null) out.Tsol = [pct(ra.Tsol), row.Tsol];
    out.colorR = [fixed(ra.colorR.a, 2), fixed(ra.colorR.b, 2)];
    out.colorT = [fixed(ra.colorT.a, 2), fixed(ra.colorT.b, 2)];
    return out;
}

const pair = v => '[' + v.map(x => (typeof x === 'string' ? x : JSON.stringify(x))).join(', ') + ']';

// The text of assets/js/glazing-coatings.js for results { hard, single, double, triple } (each from run()).
export function writeCoatings(results, { date, env = defaultEnv() } = {}) {
    const h = inputHashes(), I = '      ';
    const lines = [];
    lines.push(HEADER + '(function (root) {');
    lines.push('    var C = {');
    lines.push('      "version": ' + JSON.stringify(date) + ',');
    lines.push('      "solar": ' + JSON.stringify(env.CFG.solar) + ',');
    lines.push('      "inputs": { "engine": "' + h.engine + '", "materials": "' + h.materials + '",');
    lines.push('                  "published": "' + h.published + '", "config": "' + h.config + '" },');
    lines.push('      "coatings": {');
    const classes = CLASSES.filter(c => results[c]);
    classes.forEach((cls, ci) => {
        const spec = env.CFG.classes[cls], s = shipped(results[cls], env), rows = calibrationRows(cls, env);
        const silver = s.layers.filter(L => L.m === 'Ag').reduce((a, L) => a + L.d, 0);
        lines.push(I + '  ' + JSON.stringify(cls) + ': {');
        lines.push(I + '    "label": ' + JSON.stringify(spec.label) + ', "eps": ' + fixed(s.eps, 4) + ', "epsFrom": "published U-factors, air and argon",');
        lines.push(I + '    "layers": [ ' + s.layers.map(L => '{"m":' + JSON.stringify(L.m) + ',"d":' + fixed(L.d, 2) + '}').join(', ') + ' ],');
        lines.push(I + '    "silverNm": ' + fixed(silver, 2) + ',');
        lines.push(I + '    "calibratedTo": [' + rows.map(r => JSON.stringify(r.id)).join(', ') + '],');
        lines.push(I + '    "residuals": {');
        rows.forEach((row, ri) => {
            const res = rowResiduals(row, s.layers, s.eps, env);
            const body = Object.keys(res).map(k => JSON.stringify(k) + ': ' + pair(res[k])).join(', ');
            lines.push(I + '      ' + JSON.stringify(row.id) + ': { ' + body + ' }' + (ri < rows.length - 1 ? ',' : ''));
        });
        lines.push(I + '    }');
        lines.push(I + '  }' + (ci < classes.length - 1 ? ',' : ''));
    });
    lines.push('      }');
    lines.push('    };');
    lines.push('    root.GlazingCoatings = C;');
    lines.push("    if (typeof module !== 'undefined') module.exports = C;");
    lines.push("})(typeof window !== 'undefined' ? window : globalThis);");
    return lines.join('\n') + '\n';
}

// ── --check (spec 2.6.7) ─────────────────────────────────────────────────────────────────────────────────
// Loads the committed coatings file and recomputes every residual through the page's path,
// GlazingEngine.pane(glass, mm, coating, side, 'open'), with the current engine and materials.
// Returns { ok, problems: [string], lines: [string] }.
export function check(coatingsFile = FILES.coatings) {
    const env = makeEnv(coatingsFile), C = env.C, problems = [], lines = [];
    if (!C || !C.coatings) return { ok: false, problems: ['no GlazingCoatings in ' + coatingsFile], lines };
    const h = inputHashes();
    for (const k of ['engine', 'materials', 'published', 'config']) {
        const got = C.inputs && C.inputs[k];
        if (got !== h[k]) problems.push(`input hash "${k}" changed: file ${got || '(none)'}, now ${h[k]} (${FILES[k]})`);
    }
    if (C.solar !== env.CFG.solar) problems.push(`solar "${C.solar}" in the file, "${env.CFG.solar}" in the configuration`);
    const { E } = env;
    const build = (row, fill) => E.evaluate(row.panes.map(p => E.pane(p.glass, p.mm, p.coat || 'none', p.side || 'front', 'open')),
        row.gaps.map(w => ({ fill, width: w / 1000 })), 1, env.opts);
    for (const cls of CLASSES) {
        const c = C.coatings[cls];
        if (!c) { problems.push('class ' + cls + ' missing'); continue; }
        const want = calibrationRows(cls, env).map(r => r.id);
        if (JSON.stringify(c.calibratedTo) !== JSON.stringify(want)) problems.push(`${cls}: calibratedTo ${JSON.stringify(c.calibratedTo)}, published.json has ${JSON.stringify(want)}`);
        for (const id of Object.keys(c.residuals || {})) {
            const row = env.PUB.rows.find(r => r.id === id);
            if (!row) { problems.push(`${cls}: row ${id} is not in published.json`); continue; }
            const ra = build(row, 'air'), rr = row.Uar != null ? build(row, 'argon') : null;
            const now = { VT: 100 * ra.Tvis, Rout: 100 * ra.Rvis, Rin: 100 * ra.RvisIn, SHGC: ra.SHGC, Uair: ra.U / BTU,
                Uar: rr ? rr.U / BTU : NaN, U: ra.U / BTU, UV: 100 * env.tuv(ra), Tsol: 100 * ra.Tsol,
                colorR: [ra.colorR.a, ra.colorR.b], colorT: [ra.colorT.a, ra.colorT.b] };
            const stored = c.residuals[id], expectKeys = Object.keys(rowResidualKeys(row));
            if (JSON.stringify(Object.keys(stored)) !== JSON.stringify(expectKeys)) problems.push(`${cls} ${id}: quantities ${Object.keys(stored).join(',')}, expected ${expectKeys.join(',')}`);
            for (const q of Object.keys(stored)) {
                const tol = CHECK_TOL[q];
                if (tol == null) { problems.push(`${cls} ${id}: unknown quantity ${q}`); continue; }
                if (q === 'colorR' || q === 'colorT') {
                    for (let j = 0; j < 2; j++) {
                        const d = now[q][j] - stored[q][j];
                        if (!(Math.abs(d) <= tol)) problems.push(`${cls} ${id} ${q}[${j}]: file ${stored[q][j]}, now ${now[q][j].toFixed(3)} (tolerance ${tol})`);
                    }
                    lines.push(`  ${cls.padEnd(6)} ${id.padEnd(18)} ${q.padEnd(6)} file ${stored[q].join(', ')}  now ${now[q].map(v => v.toFixed(2)).join(', ')}`);
                    continue;
                }
                const d = now[q] - stored[q][0];
                if (!(Math.abs(d) <= tol)) problems.push(`${cls} ${id} ${q}: file ${stored[q][0]}, now ${now[q].toFixed(4)} (tolerance ${tol})`);
                if (stored[q][1] !== row[q]) problems.push(`${cls} ${id} ${q}: published value ${stored[q][1]} in the file, ${row[q]} in published.json`);
                lines.push(`  ${cls.padEnd(6)} ${id.padEnd(18)} ${q.padEnd(6)} file ${String(stored[q][0]).padStart(6)}  now ${now[q].toFixed(4).padStart(9)}  published ${stored[q][1]}`);
            }
        }
    }
    return { ok: problems.length === 0, problems, lines };
}
// The quantities a row's residuals hold, in output order.
function rowResidualKeys(row) {
    const k = {};
    for (const q of ['VT', 'Rout', 'Rin', 'SHGC', 'Uair']) if (row[q] != null) k[q] = 1;
    if (row.Uar != null) k.Uar = 1;
    for (const q of ['U', 'UV', 'Tsol']) if (row[q] != null) k[q] = 1;
    k.colorR = 1; k.colorT = 1;
    return k;
}

// ── CLI ──────────────────────────────────────────────────────────────────────────────────────────────────
function report(cls, res, env) {
    const s = shipped(res, env);
    console.log(`\n== ${cls}: objective ${res.f.toFixed(2)}, eps ${s.eps.toFixed(4)}, ${res.seconds.toFixed(0)} s`);
    console.log('   layers (nm, glass outward): ' + s.layers.map(L => L.m + ' ' + L.d.toFixed(2)).join(' / '));
    for (const row of env.PUB.rows.filter(r => r.class === cls)) {
        const r = rowResiduals(row, s.layers, s.eps, env);
        console.log('   ' + (row.role || '').padEnd(10) + row.id.padEnd(18) + Object.keys(r).map(k => k + ' ' + r[k].join('/')).join('  '));
    }
}

export function main(argv = process.argv.slice(2)) {
    const arg = name => { const a = argv.find(x => x === '--' + name || x.startsWith('--' + name + '=')); return a == null ? null : a.includes('=') ? a.slice(a.indexOf('=') + 1) : true; };
    const unknown = argv.filter(a => !/^--(check|class|date|out)(=|$)/.test(a));
    if (unknown.length) { console.error('Unknown argument(s): ' + unknown.join(' ') + '\nUsage: node _scripts/calibrate_glazing_coatings.mjs [--class=single] [--check] [--date=YYYY-MM-DD] [--out=file]'); return 2; }
    if (arg('check')) {
        const t0 = Date.now(), r = check();
        if (process.env.VERBOSE) r.lines.forEach(l => console.log(l));
        if (r.ok) { console.log(`ok: ${FILES.coatings} matches the current engine, materials, published values and configuration (${Date.now() - t0} ms)`); return 0; }
        console.error(`FAIL: ${FILES.coatings} has drifted (${r.problems.length} problem${r.problems.length > 1 ? 's' : ''}); rerun the calibration:`);
        r.problems.forEach(p => console.error('  ' + p));
        return 1;
    }
    const date = arg('date') || new Date().toISOString().slice(0, 10);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) { console.error('--date must be YYYY-MM-DD'); return 2; }
    const classArg = arg('class'), classes = classArg && classArg !== true ? String(classArg).split(',') : CLASSES;
    for (const c of classes) if (!CLASSES.includes(c)) { console.error('Unknown class ' + c + ' (hard, single, double, triple)'); return 2; }
    const env = defaultEnv(), results = {};
    for (const cls of classes) { results[cls] = run(cls, env, m => console.log(m)); report(cls, results[cls], env); }
    const out = arg('out');
    if (classArg && !out) { console.log('\n(--class given: nothing written; add --out=<file> to write these classes)'); return 0; }
    const text = writeCoatings(results, { date, env });
    const file = out && out !== true ? path.resolve(String(out)) : abs(FILES.coatings);
    fs.writeFileSync(file, text);
    console.log(`\nwrote ${path.relative(ROOT, file) || file} (${Buffer.byteLength(text)} bytes)`);
    return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();

"""Build the optical-constant and solar-spectrum tables of the open-data glazing model.

    python _scripts/build_glazing_materials.py           regenerate both files
    python _scripts/build_glazing_materials.py --check   regenerate in memory; exit 1 if a committed file differs

Inputs (all in the repository, no network; pinned in _scripts/glazing_sources.json by commit and SHA-256):
  _scripts/data/rii/*.yml, LICENSE         refractiveindex.info database files (CC0 1.0)
  _scripts/data/wce/standardData.cpp       LBNL Windows-CalcEngine standard spectra (BSD-style, License.txt beside it)
  assets/js/glazing-weights.js             only its wavelength grid is read, and asserted
Outputs (UTF-8, LF):
  assets/js/glazing-materials.js           GlazingMaterials: n and k of 14 materials on 300-2500 nm in 5 nm steps
  assets/js/glazing-solar-e891.js          GlazingSolarE891: ASTM E891 direct normal solar weights in the same bins

Physics, written from the cited sources:
  - refractiveindex.info dispersion formulas 1 (Sellmeier) and 5 (power series), and linear interpolation of
    tabulated n and k (M. N. Polyanskiy, Sci. Data 11, 94 (2024)), sampled at the grid points;
  - Drude-Lorentz dielectric function and Bruggeman effective-medium roughness layer for SnO2 and SnO2:F
    (K. von Rottkay and M. Rubin, Mater. Res. Soc. Symp. Proc. 426, 449 (1996), LBNL-38586, Table 1 and eq. 2);
  - the E891 table integrated into 5 nm bins exactly as _scripts/build_glazing_weights.py bins ASTM G173.
Standard library only.
"""

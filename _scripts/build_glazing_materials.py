DATA = os.path.join(ROOT, '_scripts', 'data')
WEIGHTS = os.path.join(ROOT, 'assets', 'js', 'glazing-weights.js')
OUT_MATERIALS = os.path.join(ROOT, 'assets', 'js', 'glazing-materials.js')
OUT_E891 = os.path.join(ROOT, 'assets', 'js', 'glazing-solar-e891.js')

EV_NM = 1239.84198          # photon energy in eV times wavelength in nm


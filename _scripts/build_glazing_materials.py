def fail(msg):
    print('build_glazing_materials.py: ' + msg, file=sys.stderr)
    sys.exit(1)


def read_bytes(path):
    try:
        with open(path, 'rb') as f:
            return f.read()
    except OSError as e:
        fail('cannot read %s (%s)' % (os.path.relpath(path, ROOT), e.strerror))


def verified(rel, sha256):
    """Raw bytes of _scripts/data/<rel>, after checking their SHA-256 against the pinned value."""
    path = os.path.join(DATA, rel)
    raw = read_bytes(path)
    got = hashlib.sha256(raw).hexdigest()
    if len(sha256) != 64 or got != sha256:
        fail('SHA-256 mismatch for %s: expected %s, got %s' % (os.path.relpath(path, ROOT).replace(os.sep, '/'), sha256, got))
    return raw


def local_name(repo_path):
    """database/data/glass/misc/soda-lime/nk/Rubin-clear.yml -> rii/glass_misc_soda-lime_nk_Rubin-clear.yml"""
    return 'rii/' + repo_path.replace('database/data/', '', 1).replace('/', '_')


# ── refractiveindex.info YAML (only the subset these files use) ────────────────────────────────────────────

def parse_yaml(text):
    """Return { ref, comment, doi, data } from a refractiveindex.info YAML file.

    ref and comment are the REFERENCES and COMMENTS literal blocks with HTML tags stripped and whitespace
    collapsed; doi is the first https://doi.org/ link; data is the list of DATA items, each
    { type, range?, coef?, rows? }. An unsupported item type is a fatal error."""
    def block(key):
        m = re.search(r'^' + key + r':\s*\|\s*\n((?:[ \t]+.*\n?)*)', text, re.M)
        return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m.group(1))).strip() if m else ''
    if 'DATA:' not in text:
        raise ValueError('no DATA block')
    items = []
    for part in re.split(r'\n\s*-\s*type:\s*', text.split('DATA:', 1)[1])[1:]:
        typ = part.split('\n', 1)[0].strip()
        if typ not in ('tabulated nk', 'tabulated n', 'tabulated k', 'formula 1', 'formula 5'):
            raise ValueError('unsupported DATA type "%s"' % typ)
        it = {'type': typ}
        m = re.search(r'wavelength_range:\s*([^\n]+)', part)
        if m:
            it['range'] = [float(x) for x in m.group(1).split()]
        m = re.search(r'coefficients:\s*([^\n]+)', part)
        if m:
            it['coef'] = [float(x) for x in m.group(1).split()]
        m = re.search(r'data:\s*\|\s*\n((?:[ \t]+[-+0-9.eE \t]+\n?)*)', part)
        if m:
            it['rows'] = [[float(v) for v in ln.split()] for ln in m.group(1).strip().split('\n') if ln.strip()]
        if typ.startswith('tabulated') and not it.get('rows'):
            raise ValueError('empty "%s" table' % typ)
        if typ.startswith('formula') and ('coef' not in it or 'range' not in it):
            raise ValueError('"%s" without coefficients or wavelength_range' % typ)
        items.append(it)
    if not items:
        raise ValueError('no DATA items')
    doi = re.search(r'https://doi\.org/[^"\s<]+', text)
    return {'ref': block('REFERENCES'), 'comment': block('COMMENTS'), 'doi': doi.group(0) if doi else '', 'data': items}


def interp(xs, ys, x):
    """Linear interpolation, clamped to the end values outside the table."""
    if x <= xs[0]:
        return ys[0]
    if x >= xs[-1]:
        return ys[-1]
    lo, hi = 0, len(xs) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if xs[mid] <= x:
            lo = mid
        else:
            hi = mid
    t = (x - xs[lo]) / (xs[hi] - xs[lo])
    return ys[lo] + t * (ys[hi] - ys[lo])


def _table(xs, ys):
    return lambda um: interp(xs, ys, um)


def nk_function(parsed):
    """(n(um), k(um)) from the parsed DATA items. Formulas are evaluated with the wavelength clamped to their
    wavelength_range; tables are interpolated linearly and clamped to their end values. Missing k is 0."""
    nf = kf = None
    for it in parsed['data']:
        t, rows = it['type'], it.get('rows')
        if t == 'tabulated nk':
            nf = _table([r[0] for r in rows], [r[1] for r in rows])
            kf = _table([r[0] for r in rows], [r[2] for r in rows])
        elif t == 'tabulated k':
            kf = _table([r[0] for r in rows], [r[1] for r in rows])
        elif t == 'tabulated n':
            nf = _table([r[0] for r in rows], [r[1] for r in rows])
        elif t == 'formula 1':      # Sellmeier: n^2 = 1 + C1 + sum Ci lam^2 / (lam^2 - Cj^2)
            c, (lo, hi) = it['coef'], it['range']

            def f1(um, c=c, lo=lo, hi=hi):
                x = min(max(um, lo), hi)
                s = 1 + c[0]
                for i in range(1, len(c) - 1, 2):
                    s += c[i] * x * x / (x * x - c[i + 1] ** 2)
                return math.sqrt(s)
            nf = f1
        elif t == 'formula 5':      # n = C1 + sum Ci lam^Cj
            c, (lo, hi) = it['coef'], it['range']

            def f5(um, c=c, lo=lo, hi=hi):
                x = min(max(um, lo), hi)
                s = c[0]
                for i in range(1, len(c) - 1, 2):
                    s += c[i] * x ** c[i + 1]
                return s
            nf = f5
    if nf is None:
        raise ValueError('no refractive index (n) in DATA')
    if kf is None:
        kf = lambda um: 0.0
    return nf, kf


# ── analytic models (von Rottkay & Rubin 1996) ─────────────────────────────────────────────────────────────

def drude_lorentz(params, nm):
    """(eps, N) at wavelength nm: eps(E) = einf - AD/(E^2 + i GD E) + AL/(EL^2 - E^2 - i GL E), E in eV,
    N = sqrt(eps) with Im N >= 0, so (n, k) = (Re N, Im N)."""
    E = EV_NM / nm
    eps = params['einf'] + 0j
    if params['AD']:
        eps -= params['AD'] / (E * E + 1j * params['GD'] * E)
    if params['AL']:
        eps += params['AL'] / (params['EL'] ** 2 - E * E - 1j * params['GL'] * E)
    N = cmath.sqrt(eps)
    if N.imag < 0:
        N = -N
    return eps, N


def bruggeman(eh, ev, fvoid):
    """N of a Bruggeman mixture of host eh (fraction 1 - fvoid) and void ev: the root of
    2 eps^2 - B eps - eh ev = 0, B = (3 fh - 1) eh + (3 fv - 1) ev, with Im eps >= 0 (the larger real part
    if both qualify), then N = sqrt(eps) with Im N >= 0."""
    fh, fv = 1 - fvoid, fvoid
    B = (3 * fh - 1) * eh + (3 * fv - 1) * ev
    disc = cmath.sqrt(B * B + 8 * eh * ev)
    best = None
    for r in ((B + disc) / 4, (B - disc) / 4):
        if r.imag >= -1e-12 and (best is None or r.real > best.real):
            best = r
    if best is None:
        raise ValueError('Bruggeman: no root with Im(eps) >= 0')
    N = cmath.sqrt(best)
    return N if N.imag >= 0 else -N


# ── sampling and rounding ──────────────────────────────────────────────────────────────────────────────────

def sig(x, digits, floor=1e-10):
    """Round to significant digits; magnitudes below floor become 0."""
    if abs(x) < floor:
        return 0
    return float('%.*g' % (digits, x))


def grid_nm(grid):
    return [grid['start'] + i * grid['step'] for i in range(grid['n'])]


def sample(material, lam=None, models=None):
    """(n[441], k[441] or 0) of one material on the grid: n to 5 significant digits, k to 4, |k| < 1e-10 -> 0,
    and the scalar 0 when every k is 0. material is { 'nk': (nf, kf) } for a YAML material, or a model entry
    of glazing_sources.json ('drude-lorentz', or 'bruggeman' with its host in models)."""
    if 'nk' in material:
        nf, kf = material['nk']
        ns = [sig(nf(l / 1000), 5) for l in lam]
        ks = [sig(kf(l / 1000), 4) for l in lam]
    else:
        ns, ks = [], []
        for l in lam:
            if material['kind'] == 'drude-lorentz':
                _, N = drude_lorentz(material, l)
            elif material['kind'] == 'bruggeman':
                eh, _ = drude_lorentz(models[material['host']], l)
                N = bruggeman(eh, 1 + 0j, material['fvoid'])
            else:
                raise ValueError('unknown model kind ' + material['kind'])
            ns.append(sig(N.real, 5))
            ks.append(sig(N.imag, 4))
    if not any(ks):
        ks = 0
    return ns, ks


# ── E891 ───────────────────────────────────────────────────────────────────────────────────────────────────

def e891_table(text, name):
    """[(nm, value)] pairs of the CSeries function `name` in standardData.cpp."""
    i = text.find(name + '()')
    if i < 0:
        raise ValueError('function %s() not found' % name)
    j = text.find('return', i)
    start = text.find('{', j)
    depth, k = 0, start
    while k < len(text):
        if text[k] == '{':
            depth += 1
        elif text[k] == '}':
            depth -= 1
            if depth == 0:
                break
        k += 1
    body = text[start:k + 1]
    return [(float(a) * 1000, float(b)) for a, b in re.findall(r'\{\s*([0-9.]+)\s*,\s*([0-9.eE+-]+)\s*\}', body)]


def e891_weights(path, lam=None, spec=None):
    """441 normalized weights: the E891 table interpolated linearly (zero outside the table), integrated over
    each 5 nm bin [c - 2.5, c + 2.5) with 0.25 nm midpoint sub-steps, as _scripts/build_glazing_weights.py
    bins ASTM G173, normalized to sum 1 over the grid and rounded to 6 significant digits."""
    with open(path, 'rb') as f:
        text = f.read().decode('utf-8')
    pts = e891_table(text, (spec or {}).get('table', 'solarRadiationASTM_E891_87_Table1'))
    if spec:
        lo, hi = spec['range_um']
        if len(pts) != spec['points'] or abs(pts[0][0] - lo * 1000) > 1e-9 or abs(pts[-1][0] - hi * 1000) > 1e-9:
            raise ValueError('E891 table: expected %d points from %g to %g um, found %d from %g to %g nm'
                             % (spec['points'], lo, hi, len(pts), pts[0][0] if pts else 0, pts[-1][0] if pts else 0))
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]

    def f(x):
        if x < xs[0] or x > xs[-1]:
            return 0.0
        return interp(xs, ys, x)
    w = []
    for c in lam:
        s, x = 0.0, c - 2.5 + 0.125
        while x < c + 2.5:
            s += f(x) * 0.25
            x += 0.25
        w.append(s)
    tot = sum(w)
    return [sig(v / tot, 6) for v in w]


def e891_tuv_table(path, spec=None):
    """The E891 table points from 310 to 380 nm, [[nm, value]], for the ultraviolet transmittance of LBNL WINDOW's
    NFRC standard (W5_NFRC_2003.std, method TUV: ASTM E891 source, source wavelength set, trapezoidal rule,
    0.31-0.38 um). The page integrates the transmittance over these points itself (GlazingBeta.tuvNFRC)."""
    with open(path, 'rb') as f:
        text = f.read().decode('utf-8')
    pts = e891_table(text, (spec or {}).get('table', 'solarRadiationASTM_E891_87_Table1'))
    out = [[round(x, 6), y] for x, y in pts if 310 - 1e-9 <= x <= 380 + 1e-9]
    out = [[int(x) if x == int(x) else x, y] for x, y in out]
    if len(out) != 12 or out[0][0] != 310 or out[-1][0] != 380:
        raise ValueError('E891 table: expected 12 points from 310 to 380 nm for TUV, found %d' % len(out))
    return out


# ── output ─────────────────────────────────────────────────────────────────────────────────────────────────

def write_js(path, header, global_name, obj):
    """Return the text of a classic UMD script that sets window[global_name] (and module.exports) to obj;
    write it to path (UTF-8, LF) unless path is None."""
    var = 'S' if 'Solar' in global_name else 'M'
    js = (header +
          '(function (root) {\n'
          '    var ' + var + ' = ' + json.dumps(obj, separators=(',', ':'), ensure_ascii=False) + ';\n'
          '    root.' + global_name + ' = ' + var + ';\n'
          '    if (typeof module !== \'undefined\') module.exports = ' + var + ';\n'
          '})(typeof window !== \'undefined\' ? window : globalThis);\n')
    if path is not None:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'wb') as f:
            f.write(js.encode('utf-8'))
    return js


def engine_grid():
    """The grid of assets/js/glazing-weights.js (window.GlazingWeights = {...})."""
    text = read_bytes(WEIGHTS).decode('utf-8')
    m = re.search(r'"grid"\s*:\s*\{\s*"start"\s*:\s*(\d+)\s*,\s*"step"\s*:\s*(\d+)\s*,\s*"n"\s*:\s*(\d+)\s*\}', text)
    if not m:
        fail('no grid found in assets/js/glazing-weights.js')
    return {'start': int(m.group(1)), 'step': int(m.group(2)), 'n': int(m.group(3))}


def build():
    """Verify every input, then return { path: text } for both outputs."""
    try:
        S = json.loads(read_bytes(SOURCES).decode('utf-8'))
    except ValueError as e:
        fail('_scripts/glazing_sources.json is not valid JSON (%s)' % e)
    G = S['grid']
    if engine_grid() != G:
        fail('grid %s of glazing_sources.json does not match assets/js/glazing-weights.js %s' % (G, engine_grid()))
    lam = grid_nm(G)
    rii, sol = S['refractiveindex'], S['solarE891']

    # 1. Hashes of every input, before any parsing.
    verified(rii['licenseFile']['file'], rii['licenseFile']['sha256'])
    raw = {m['id']: verified(local_name(m['path']), m['sha256']) for m in S['materials']}
    verified(sol['file'], sol['sha256'])
    license_text = verified(sol['licenseFile']['file'], sol['licenseFile']['sha256']).decode('utf-8')

    # 2. Tabulated materials.
    mats = {}
    for m in S['materials']:
        try:
            y = parse_yaml(raw[m['id']].decode('utf-8'))
            n, k = sample({'nk': nk_function(y)}, lam)
        except ValueError as e:
            fail('%s: %s' % (local_name(m['path']), e))
        if not y['doi']:
            fail('%s: no https://doi.org/ link in REFERENCES' % local_name(m['path']))
        entry = {'label': m['label'], 'role': m['role'], 'n': n, 'k': k, 'ref': y['ref'], 'doi': y['doi'],
                 'src': rii['repo'] + '/blob/' + rii['commit'] + '/' + m['path'], 'license': rii['license']}
        if m['role'] == 'substrate':
            entry['comment'] = y['comment']
        mats[m['id']] = entry

    # 3. Analytic models.
    models = {mm['id']: mm for mm in S['models']}
    for mm in S['models']:
        n, k = sample(mm, lam, models)
        mats[mm['id']] = {'label': mm['label'], 'role': mm['role'], 'n': n, 'k': k, 'ref': mm['ref'], 'doi': '',
                          'src': S['modelSource']['src'], 'license': S['modelSource']['license']}

    # 4. E891 weights.
    try:
        w = e891_weights(os.path.join(DATA, sol['file']), lam, sol)
        tuv = e891_tuv_table(os.path.join(DATA, sol['file']), sol)
    except ValueError as e:
        fail('%s: %s' % (sol['file'], e))
    if abs(sum(w) - 1) > 1e-5:
        fail('E891 weights sum to %.8f, not 1' % sum(w))
    if '*/' in license_text:
        fail('wce/License.txt contains "*/" and cannot be embedded in a comment')
    lic = '\n'.join('   ' + line for line in license_text.replace('\r\n', '\n').split('\n'))

    return {
        OUT_MATERIALS: write_js(None, HEADER_MATERIALS, 'GlazingMaterials', {'grid': G, 'materials': mats}),
        OUT_E891: write_js(None, HEADER_E891.replace('{license}', lic), 'GlazingSolarE891', {'grid': G, 'solarE891': w, 'tuvTable': tuv}),
    }, w, lam


def main(argv):
    args = argv[1:]
    if any(a not in ('--check',) for a in args):
        fail('usage: python _scripts/build_glazing_materials.py [--check]')
    out, w, lam = build()
    rel = lambda p: os.path.relpath(p, ROOT).replace(os.sep, '/')
    if '--check' in args:
        bad = []
        for path, text in out.items():
            try:
                with open(path, 'rb') as f:
                    have = f.read().decode('utf-8').replace('\r\n', '\n')
            except OSError:
                have = None
            if have != text:
                bad.append(rel(path))
        if bad:
            fail('out of date: ' + ', '.join(bad) + ' (run python _scripts/build_glazing_materials.py)')
        print('ok: ' + ', '.join(rel(p) for p in out) + ' match the generator')
        return 0
    for path, text in out.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'wb') as f:
            f.write(text.encode('utf-8'))
        print('%s: %d bytes' % (rel(path), len(text.encode('utf-8'))))
    vis = sum(v for l, v in zip(lam, w) if 380 <= l <= 780)
    print('E891: sum %.6f, 380-780 nm fraction %.4f' % (sum(w), vis))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
